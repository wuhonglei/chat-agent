import { mkdir, readFile, rm, writeFile } from "fs/promises";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const MATERIAL_ICON_THEME_URL = "https://unpkg.com/material-icon-theme/dist/material-icons.json";
const MATERIAL_ICON_FILE_URL_PREFIX = "https://unpkg.com/material-icon-theme/icons";
const EDITOR_CONSTANTS_FILE = resolve(__dirname, "../src/constants/editor.ts");
const OUTPUT_FILE = resolve(
  __dirname,
  "../src/pages/ChatPage/components/BlockPreviewPanel/ProjectPreview/file_icons.tsx"
);
const ICONS_DIR = resolve(
  __dirname,
  "../src/pages/ChatPage/components/BlockPreviewPanel/ProjectPreview/material_icons"
);

const EXTRA_FILENAME_KEYS = [
  "gitignore",
  "npmrc",
  "prettierrc",
  "prettierignore",
  "eslintrc",
  "editorconfig",
  "gitattributes",
];

const EXTRA_EXTENSION_KEYS = [
  "pdf",
  "png",
  "jpg",
  "jpeg",
  "gif",
  "webp",
  "ico",
  "csv",
  "xls",
  "xlsx",
  "doc",
  "docx",
  "zip",
  "rar",
  "7z",
  "tar",
  "gz",
  "tgz",
  "bz2",
];

const KEY_ICON_OVERRIDES = {
  ts: "typescript",
  mts: "typescript",
  cts: "typescript",
  tsx: "react_ts",
  js: "javascript",
  mjs: "javascript",
  cjs: "javascript",
  jsx: "react",
  dockerfile: "docker",
  gitignore: "git",
  npmrc: "npm",
  prettierrc: "prettier",
  prettierignore: "prettier",
  eslintrc: "eslint",
  editorconfig: "editorconfig",
  gitattributes: "git",
};

function parseEditorExtensions(source) {
  const matches = source.matchAll(/^\s*([a-z0-9]+):\s*"/gim);
  return [...new Set(Array.from(matches, match => match[1].toLowerCase()))];
}

function makeSafeImportName(iconName) {
  return `icon_${iconName.replace(/[^a-zA-Z0-9_]/g, "_")}`;
}

async function cleanIconDirectory() {
  await rm(ICONS_DIR, { recursive: true, force: true });
  await mkdir(ICONS_DIR, { recursive: true });
}

function resolveIconSourceFileName(iconDefinition) {
  const iconPath = typeof iconDefinition?.iconPath === "string" ? iconDefinition.iconPath : "";
  const fileName = iconPath.split("/").pop() || "";
  return fileName.endsWith(".svg") ? fileName : null;
}

async function downloadIcon(iconName, iconDefinition) {
  const sourceFileName = resolveIconSourceFileName(iconDefinition);
  if (!sourceFileName) {
    return false;
  }
  const response = await fetch(`${MATERIAL_ICON_FILE_URL_PREFIX}/${sourceFileName}`);
  if (!response.ok) {
    return false;
  }
  const svg = await response.text();
  await writeFile(resolve(ICONS_DIR, `${iconName}.svg`), svg, "utf8");
  return true;
}

function buildIconLine(key, iconName) {
  const safeName = makeSafeImportName(iconName);
  return `  ${JSON.stringify(key)}: makeSvgIcon(${safeName}),`;
}

async function main() {
  const [editorConstantsSource, materialResponse] = await Promise.all([
    readFile(EDITOR_CONSTANTS_FILE, "utf8"),
    fetch(MATERIAL_ICON_THEME_URL),
  ]);

  if (!materialResponse.ok) {
    throw new Error(`Failed to fetch Material Icon Theme: ${materialResponse.status}`);
  }

  const materialJson = await materialResponse.json();
  const extensionToIcon = materialJson.fileExtensions || {};
  const iconDefinitions = materialJson.iconDefinitions || {};

  const editorExtensionKeys = parseEditorExtensions(editorConstantsSource);
  const targetKeys = [
    ...new Set([...editorExtensionKeys, ...EXTRA_FILENAME_KEYS, ...EXTRA_EXTENSION_KEYS]),
  ].sort();

  const mappedEntries = targetKeys.map(key => {
    const iconName = KEY_ICON_OVERRIDES[key] || extensionToIcon[key] || "file";
    return { key, iconName };
  });

  const candidateIconNames = [...new Set(mappedEntries.map(entry => entry.iconName))]
    .filter(iconName => typeof iconName === "string" && iconName && iconDefinitions[iconName])
    .sort();

  await cleanIconDirectory();
  const downloadedIconNames = (
    await Promise.all(
      candidateIconNames.map(async iconName => {
        const success = await downloadIcon(iconName, iconDefinitions[iconName]);
        return success ? iconName : null;
      })
    )
  ).filter(Boolean);

  const iconNames = downloadedIconNames;
  const importableIconSet = new Set(iconNames);
  const safeMappedEntries = mappedEntries.map(entry => ({
    ...entry,
    iconName: importableIconSet.has(entry.iconName) ? entry.iconName : "file",
  }));

  const importLines = iconNames
    .map(iconName => {
      const safeName = makeSafeImportName(iconName);
      return `import ${safeName} from "./material_icons/${iconName}.svg?react";`;
    })
    .join("\n");

  const output = `import {
  FileTextOutlined,
  FolderOutlined,
} from "@ant-design/icons";
import type { ReactNode } from "react";
${importLines ? `\n${importLines}` : ""}

// AUTO-GENERATED by scripts/generate-project-preview-file-icons.mjs
// Source: ${MATERIAL_ICON_THEME_URL}
// Do not edit manually.
const FOLDER_ICON = <FolderOutlined style={{ color: "#faad14" }} />;
const TEXT_ICON = <FileTextOutlined style={{ color: "#666" }} />;
const SVG_ICON_STYLE: React.CSSProperties = { width: 14, height: 14, objectFit: "contain" };
const makeSvgIcon = (IconComponent: React.ComponentType<React.SVGProps<SVGSVGElement>>): ReactNode => (
  <IconComponent style={SVG_ICON_STYLE} />
);

export const PROJECT_PREVIEW_DIRECTORY_ICONS = {
  directory: FOLDER_ICON,
  folder: FOLDER_ICON,
  file: TEXT_ICON,
${safeMappedEntries.map(entry => buildIconLine(entry.key, entry.iconName)).join("\n")}
} as const;
`;

  await writeFile(OUTPUT_FILE, output, "utf8");
  console.log(`Generated ${OUTPUT_FILE}`);
}

await main();
